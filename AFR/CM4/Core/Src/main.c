/* USER CODE BEGIN 4 */
void waysend(void *argument)
{
	int uhh = 0;
	for(;;)
	{
		if (!(SHARED_MEM->flag))
		{
			BSP_LED_Toggle(LED_YELLOW);
			for (int i = 0; i < 16; ++i)
				SHARED_MEM->buffer[i] = i * 1.1f+uhh;
			SHARED_MEM->flag = 1;
			__DSB();    // ensure the write completes
			uhh++;
		}
		BSP_LED_Toggle(LED_YELLOW);
	    osDelay(1);
	}
}

